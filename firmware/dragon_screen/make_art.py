#!/usr/bin/env python3
"""Turn art.py into firmware data and a preview.

Writes:
  ../qmk/lazydragon64/dragon_art.h   every dragon pose as 32 rows of 32-bit masks, plus the
                                     5 x 7 glyphs the screen uses (from QMK's glcdfont.c)
  dragon_art.json                    the same data for the preview page
  poses.png                          every pose, 8x, for checking the art by eye
Run from this folder: python3 make_art.py [path to qmk_firmware]
"""
import json, os, re, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
exec(open(os.path.join(HERE, "art.py")).read())
QMK = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/qmk_firmware")

EYES, WINGS, TAILS, FIRES = ("closed", "half", "open"), ("fold", "up"), ("rest", "flick"), (None, 0, 1)
poses = []
for e in EYES:
    for w in WINGS:
        for t in TAILS:
            for f in FIRES:
                g = scene(eye=e, wing=w, tail=t, fire=f)
                poses.append([sum(1 << x for x in range(32) if g[y][x]) for y in range(32)])

# glyphs: QMK's 6 x 8 font, first five columns, for the characters the screen can show
src = open(os.path.join(QMK, "drivers/oled/glcdfont.c")).read()
src = re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", src), flags=re.S)  # hex in comments would shift every glyph
body = src[src.index("font[] PROGMEM = {"):]
font = [int(h, 16) for h in re.findall(r"0x([0-9A-Fa-f]{2})", body[:body.index("};")])]
CHARS = " -0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
assert len(font) >= 256 * 6 - 32 * 6, len(font)
glyphs = [font[ord(c) * 6: ord(c) * 6 + 5] for c in CHARS]

out = os.path.join(HERE, "..", "qmk", "lazydragon64", "dragon_art.h")
with open(out, "w") as f:
    f.write("// Generated by firmware/dragon_screen/make_art.py from art.py. Do not edit by hand.\n")
    f.write("// The glyphs are from QMK's drivers/oled/glcdfont.c (GPL-2.0-or-later WITH BSD-2-Clause,\n// derived from the Adafruit GFX font).\n#pragma once\n#include <stdint.h>\n\n")
    f.write("// pose index = ((eye * 2 + wing) * 2 + tail) * 3 + fire\n")
    f.write("// eye: 0 closed, 1 half, 2 open; wing: 0 folded, 1 raised; tail: 0 resting, 1 flicked;\n// fire: 0 none, 1 and 2 the two flame frames. Row y, bit x = pixel (x, y).\n")
    f.write("#define DRAGON_POSE(eye, wing, tail, fire) ((((eye) * 2 + (wing)) * 2 + (tail)) * 3 + (fire))\n\n")
    f.write("static const uint32_t dragon_poses[%d][32] = {\n" % len(poses))
    for p in poses:
        f.write("    {" + ", ".join("0x%08x" % r for r in p) + "},\n")
    f.write("};\n\n")
    f.write('static const char dragon_font_chars[] = "%s";\n' % CHARS)
    f.write("static const uint8_t dragon_font[%d][5] = {\n" % len(glyphs))
    for c, g in zip(CHARS, glyphs):
        f.write("    {" + ", ".join("0x%02x" % b for b in g) + "}, // '%s'\n" % c)
    f.write("};\n")
json.dump({"poses": [["%08x" % r for r in p] for p in poses], "chars": CHARS, "font": [bytes(g).hex() for g in glyphs]},
          open(os.path.join(HERE, "dragon_art.json"), "w"), separators=(",", ":"))

im = Image.new("L", (12 * 36, 3 * 36), 40)
for i, p in enumerate(poses):
    ox, oy = (i % 12) * 36 + 2, (i // 12) * 36 + 2
    for y in range(32):
        for x in range(32):
            im.putpixel((ox + x, oy + y), 255 if p[y] >> x & 1 else 0)
im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(os.path.join(HERE, "poses.png"))
print("wrote %d poses, %d glyphs" % (len(poses), len(glyphs)))
